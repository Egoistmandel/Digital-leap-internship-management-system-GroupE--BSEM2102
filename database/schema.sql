-- =============================================================================
-- Digital LEAP Internship Management System
-- Database Schema — MySQL
-- =============================================================================
-- Version    : 1.0
-- Course     : COMP 217 — System Analysis and Design
-- Group      : Group E
-- Semester   : 05 (September 2026 – February 2027)
-- =============================================================================
-- All tables use InnoDB for foreign key enforcement and transactions.
-- Character set: utf8mb4 to support full Unicode including special characters.
-- =============================================================================

CREATE DATABASE IF NOT EXISTS digital_leap
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE digital_leap;

-- =============================================================================
-- 1. ROLES
-- Defines the seven system roles (D-01).
-- =============================================================================
CREATE TABLE roles (
    role_id   TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    role_name VARCHAR(50)      NOT NULL,
    CONSTRAINT pk_roles         PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_name    UNIQUE      (role_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Seed the seven roles
INSERT INTO roles (role_name) VALUES
    ('student'),
    ('leap_coordinator'),
    ('academic_supervisor'),
    ('faculty_coordinator'),
    ('faculty_mentor'),
    ('host_supervisor'),
    ('management');

-- =============================================================================
-- 2. USERS
-- Central user table. Passwords are stored as bcrypt hashes only.
-- Account starts as 'pending' until a coordinator approves it (FR-02).
-- Lockout fields support D-05 (3 attempts → lock → auto-unlock after 30 min).
-- =============================================================================
CREATE TABLE users (
    user_id         INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    full_name       VARCHAR(150)  NOT NULL,
    email           VARCHAR(150)  NOT NULL,
    password_hash   VARCHAR(255)  NOT NULL,
    status          ENUM('pending','active','locked','suspended')
                                  NOT NULL DEFAULT 'pending',
    failed_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
    locked_at       DATETIME      NULL,
    created_at      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP
                                  ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT pk_users         PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email   UNIQUE      (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 3. USER_ROLES
-- Many-to-many between users and roles.
-- A user may hold more than one role (e.g. faculty_coordinator + faculty_mentor).
-- =============================================================================
CREATE TABLE user_roles (
    user_role_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id      INT UNSIGNED NOT NULL,
    role_id      TINYINT UNSIGNED NOT NULL,
    assigned_by  INT UNSIGNED NULL,
    assigned_at  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_roles         PRIMARY KEY (user_role_id),
    CONSTRAINT uq_user_roles_pair    UNIQUE      (user_id, role_id),
    CONSTRAINT fk_ur_user            FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_ur_role            FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON DELETE RESTRICT,
    CONSTRAINT fk_ur_assigned_by     FOREIGN KEY (assigned_by)
        REFERENCES users (user_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 4. USER_SESSIONS
-- Stores API authentication tokens (Bearer token approach).
-- Token is a 64-character hex string generated by random_bytes(32).
-- Sessions expire after 8 hours by default.
-- =============================================================================
CREATE TABLE user_sessions (
    session_id INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    user_id    INT UNSIGNED  NOT NULL,
    token      VARCHAR(64)   NOT NULL,
    expires_at DATETIME      NOT NULL,
    created_at DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_sessions       PRIMARY KEY (session_id),
    CONSTRAINT uq_user_sessions_token UNIQUE      (token),
    CONSTRAINT fk_sessions_user       FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 5. HOST_ORGANISATIONS
-- Companies or organisations that host interns.
-- Must be approved by the Coordinator before being available for placements (FR-02).
-- =============================================================================
CREATE TABLE host_organisations (
    org_id        INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    org_name      VARCHAR(200)  NOT NULL,
    industry      VARCHAR(100)  NULL,
    address       TEXT          NULL,
    contact_name  VARCHAR(150)  NULL,
    contact_email VARCHAR(150)  NULL,
    contact_phone VARCHAR(30)   NULL,
    approved_by   INT UNSIGNED  NULL,
    approved_at   DATETIME      NULL,
    status        ENUM('pending','approved','suspended')
                                NOT NULL DEFAULT 'pending',
    created_at    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_host_orgs         PRIMARY KEY (org_id),
    CONSTRAINT fk_host_approved_by  FOREIGN KEY (approved_by)
        REFERENCES users (user_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 6. HOST_VACANCIES
-- Individual internship positions offered by a host organisation.
-- capacity: how many interns can fill this vacancy.
-- filled_count: incremented when a placement is confirmed.
-- =============================================================================
CREATE TABLE host_vacancies (
    vacancy_id   INT UNSIGNED    NOT NULL AUTO_INCREMENT,
    org_id       INT UNSIGNED    NOT NULL,
    title        VARCHAR(150)    NOT NULL,
    description  TEXT            NULL,
    capacity     TINYINT UNSIGNED NOT NULL DEFAULT 1,
    filled_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
    start_date   DATE            NULL,
    end_date     DATE            NULL,
    is_active    TINYINT(1)      NOT NULL DEFAULT 1,
    created_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_host_vacancies     PRIMARY KEY (vacancy_id),
    CONSTRAINT fk_vacancies_org      FOREIGN KEY (org_id)
        REFERENCES host_organisations (org_id) ON DELETE CASCADE,
    CONSTRAINT chk_vacancy_dates     CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT chk_filled_capacity   CHECK (filled_count <= capacity)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 7. STUDENT_PROFILES
-- Extended profile for students (one-to-one with users).
-- =============================================================================
CREATE TABLE student_profiles (
    profile_id     INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    user_id        INT UNSIGNED  NOT NULL,
    student_number VARCHAR(30)   NOT NULL,
    programme      VARCHAR(150)  NULL,
    semester       TINYINT UNSIGNED NULL,
    phone          VARCHAR(30)   NULL,
    eligibility    ENUM('not_verified','eligible','ineligible')
                                 NOT NULL DEFAULT 'not_verified',
    verified_by    INT UNSIGNED  NULL,
    verified_at    DATETIME      NULL,
    created_at     DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_student_profiles      PRIMARY KEY (profile_id),
    CONSTRAINT uq_student_profiles_user UNIQUE      (user_id),
    CONSTRAINT uq_student_number        UNIQUE      (student_number),
    CONSTRAINT fk_sp_user               FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_sp_verified_by        FOREIGN KEY (verified_by)
        REFERENCES users (user_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 8. PLACEMENTS
-- Core entity representing a student's internship at a host organisation.
-- Lifecycle: pending → coordinator_approved → awaiting_host →
--            confirmed → active → completed  (or rejected at any stage).
-- =============================================================================
CREATE TABLE placements (
    placement_id           INT UNSIGNED NOT NULL AUTO_INCREMENT,
    student_id             INT UNSIGNED NOT NULL,
    vacancy_id             INT UNSIGNED NOT NULL,
    org_id                 INT UNSIGNED NOT NULL,
    coordinator_id         INT UNSIGNED NOT NULL,
    academic_supervisor_id INT UNSIGNED NULL,
    host_supervisor_id     INT UNSIGNED NULL,
    preferred_sector       VARCHAR(100) NULL,
    status                 ENUM(
                               'pending',
                               'coordinator_approved',
                               'awaiting_host',
                               'confirmed',
                               'active',
                               'completed',
                               'rejected'
                           ) NOT NULL DEFAULT 'pending',
    rejection_reason       TEXT         NULL,
    start_date             DATE         NULL,
    end_date               DATE         NULL,
    created_at             DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
                                        ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT pk_placements              PRIMARY KEY (placement_id),
    CONSTRAINT fk_pl_student              FOREIGN KEY (student_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pl_vacancy              FOREIGN KEY (vacancy_id)
        REFERENCES host_vacancies (vacancy_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pl_org                  FOREIGN KEY (org_id)
        REFERENCES host_organisations (org_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pl_coordinator          FOREIGN KEY (coordinator_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pl_academic_supervisor  FOREIGN KEY (academic_supervisor_id)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_pl_host_supervisor      FOREIGN KEY (host_supervisor_id)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT chk_placement_dates        CHECK (end_date IS NULL OR end_date >= start_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 9. PLACEMENT_LETTERS
-- Auto-generated letter produced when coordinator approves a placement (FR-05).
-- =============================================================================
CREATE TABLE placement_letters (
    letter_id      INT UNSIGNED NOT NULL AUTO_INCREMENT,
    placement_id   INT UNSIGNED NOT NULL,
    generated_by   INT UNSIGNED NOT NULL,
    generated_at   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    letter_content TEXT         NOT NULL,
    CONSTRAINT pk_placement_letters      PRIMARY KEY (letter_id),
    CONSTRAINT uq_placement_letters_pl   UNIQUE      (placement_id),
    CONSTRAINT fk_pl_letters_placement   FOREIGN KEY (placement_id)
        REFERENCES placements (placement_id) ON DELETE CASCADE,
    CONSTRAINT fk_pl_letters_generated   FOREIGN KEY (generated_by)
        REFERENCES users (user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 10. LOGBOOK_ENTRIES
-- Weekly logbook submitted by students (FR-07).
-- entry_date must fall within the placement's start_date and end_date.
-- One entry per week per placement enforced by UNIQUE constraint.
-- =============================================================================
CREATE TABLE logbook_entries (
    entry_id      INT UNSIGNED    NOT NULL AUTO_INCREMENT,
    placement_id  INT UNSIGNED    NOT NULL,
    student_id    INT UNSIGNED    NOT NULL,
    week_number   TINYINT UNSIGNED NOT NULL,
    entry_date    DATE            NOT NULL,
    activities    TEXT            NOT NULL,
    skills_gained TEXT            NULL,
    hours_worked  DECIMAL(4,1)    NOT NULL,
    status        ENUM('draft','submitted','approved','revision_requested')
                                  NOT NULL DEFAULT 'draft',
    submitted_at  DATETIME        NULL,
    created_at    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP
                                  ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT pk_logbook_entries            PRIMARY KEY (entry_id),
    CONSTRAINT uq_logbook_week               UNIQUE      (placement_id, week_number),
    CONSTRAINT fk_le_placement               FOREIGN KEY (placement_id)
        REFERENCES placements (placement_id) ON DELETE CASCADE,
    CONSTRAINT fk_le_student                 FOREIGN KEY (student_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_hours_worked              CHECK (hours_worked >= 0 AND hours_worked <= 168)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 11. LOGBOOK_REVIEWS
-- Records supervisor decisions on logbook entries (FR-08).
-- Multiple reviews are possible per entry (revision loop history).
-- =============================================================================
CREATE TABLE logbook_reviews (
    review_id   INT UNSIGNED NOT NULL AUTO_INCREMENT,
    entry_id    INT UNSIGNED NOT NULL,
    reviewer_id INT UNSIGNED NOT NULL,
    decision    ENUM('approved','revision_requested') NOT NULL,
    comments    TEXT         NULL,
    reviewed_at DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_logbook_reviews    PRIMARY KEY (review_id),
    CONSTRAINT fk_lr_entry           FOREIGN KEY (entry_id)
        REFERENCES logbook_entries (entry_id) ON DELETE CASCADE,
    CONSTRAINT fk_lr_reviewer        FOREIGN KEY (reviewer_id)
        REFERENCES users (user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 12. SUPERVISORY_VISITS
-- Visits scheduled by academic supervisors to host sites (FR-09).
-- =============================================================================
CREATE TABLE supervisory_visits (
    visit_id       INT UNSIGNED NOT NULL AUTO_INCREMENT,
    placement_id   INT UNSIGNED NOT NULL,
    supervisor_id  INT UNSIGNED NOT NULL,
    scheduled_date DATE         NOT NULL,
    scheduled_time TIME         NULL,
    location       VARCHAR(255) NULL,
    status         ENUM('scheduled','completed','cancelled')
                                NOT NULL DEFAULT 'scheduled',
    created_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_supervisory_visits   PRIMARY KEY (visit_id),
    CONSTRAINT fk_sv_placement         FOREIGN KEY (placement_id)
        REFERENCES placements (placement_id) ON DELETE CASCADE,
    CONSTRAINT fk_sv_supervisor        FOREIGN KEY (supervisor_id)
        REFERENCES users (user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 13. VISIT_REPORTS
-- Report filed by supervisor after completing a visit (FR-09).
-- One report per visit.
-- =============================================================================
CREATE TABLE visit_reports (
    report_id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
    visit_id           INT UNSIGNED NOT NULL,
    supervisor_id      INT UNSIGNED NOT NULL,
    observations       TEXT         NOT NULL,
    recommendations    TEXT         NULL,
    student_performance TEXT        NULL,
    submitted_at       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_visit_reports        PRIMARY KEY (report_id),
    CONSTRAINT uq_visit_reports_visit  UNIQUE      (visit_id),
    CONSTRAINT fk_vr_visit             FOREIGN KEY (visit_id)
        REFERENCES supervisory_visits (visit_id) ON DELETE CASCADE,
    CONSTRAINT fk_vr_supervisor        FOREIGN KEY (supervisor_id)
        REFERENCES users (user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 14. HOST_EVALUATIONS
-- End-of-placement evaluation submitted by the host supervisor (FR-10).
-- criteria stored as JSON for flexibility (rubric defined by coordinator).
-- =============================================================================
CREATE TABLE host_evaluations (
    evaluation_id      INT UNSIGNED   NOT NULL AUTO_INCREMENT,
    placement_id       INT UNSIGNED   NOT NULL,
    host_supervisor_id INT UNSIGNED   NOT NULL,
    criteria           JSON           NOT NULL,
    overall_score      DECIMAL(5,2)   NULL,
    comments           TEXT           NULL,
    status             ENUM('draft','submitted') NOT NULL DEFAULT 'draft',
    submitted_at       DATETIME       NULL,
    created_at         DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_host_evaluations       PRIMARY KEY (evaluation_id),
    CONSTRAINT uq_host_evaluations_pl    UNIQUE      (placement_id),
    CONSTRAINT fk_he_placement           FOREIGN KEY (placement_id)
        REFERENCES placements (placement_id) ON DELETE CASCADE,
    CONSTRAINT fk_he_host_supervisor     FOREIGN KEY (host_supervisor_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_overall_score         CHECK (overall_score IS NULL OR
                                                (overall_score >= 0 AND overall_score <= 100))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 15. ASSESSMENT_COMPONENTS
-- Configurable assessment components defined by the Coordinator (D-02).
-- Weights must sum to 100 — enforced at application level.
-- Third component name is TBC pending lecturer confirmation (U-01).
-- =============================================================================
CREATE TABLE assessment_components (
    component_id   INT UNSIGNED   NOT NULL AUTO_INCREMENT,
    component_name VARCHAR(100)   NOT NULL,
    description    TEXT           NULL,
    weight_percent DECIMAL(5,2)   NOT NULL,
    is_active      TINYINT(1)     NOT NULL DEFAULT 1,
    created_by     INT UNSIGNED   NOT NULL,
    created_at     DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_assessment_components   PRIMARY KEY (component_id),
    CONSTRAINT chk_weight_range           CHECK (weight_percent > 0 AND weight_percent <= 100),
    CONSTRAINT fk_ac_created_by           FOREIGN KEY (created_by)
        REFERENCES users (user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 16. ASSESSMENT_MARKS
-- Individual scores submitted per component per placement (FR-11).
-- One mark per component per placement enforced by UNIQUE constraint.
-- =============================================================================
CREATE TABLE assessment_marks (
    mark_id      INT UNSIGNED   NOT NULL AUTO_INCREMENT,
    placement_id INT UNSIGNED   NOT NULL,
    component_id INT UNSIGNED   NOT NULL,
    assessor_id  INT UNSIGNED   NOT NULL,
    score        DECIMAL(5,2)   NOT NULL,
    max_score    DECIMAL(5,2)   NOT NULL DEFAULT 100.00,
    comments     TEXT           NULL,
    submitted_at DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_assessment_marks        PRIMARY KEY (mark_id),
    CONSTRAINT uq_marks_placement_comp    UNIQUE      (placement_id, component_id),
    CONSTRAINT fk_am_placement            FOREIGN KEY (placement_id)
        REFERENCES placements (placement_id) ON DELETE CASCADE,
    CONSTRAINT fk_am_component            FOREIGN KEY (component_id)
        REFERENCES assessment_components (component_id) ON DELETE RESTRICT,
    CONSTRAINT fk_am_assessor             FOREIGN KEY (assessor_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_score_range            CHECK (score >= 0 AND score <= max_score)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 17. GRADE_CONFIGURATIONS
-- Configurable grade bands (D-03). No official boundaries are assumed.
-- Coordinator populates this table before results are computed.
-- =============================================================================
CREATE TABLE grade_configurations (
    config_id   INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    grade_band  VARCHAR(5)    NOT NULL,
    min_score   DECIMAL(5,2)  NOT NULL,
    max_score   DECIMAL(5,2)  NOT NULL,
    gpa_points  DECIMAL(3,2)  NULL,
    description VARCHAR(100)  NULL,
    is_active   TINYINT(1)    NOT NULL DEFAULT 1,
    CONSTRAINT pk_grade_configurations    PRIMARY KEY (config_id),
    CONSTRAINT uq_grade_band              UNIQUE      (grade_band),
    CONSTRAINT chk_grade_score_range      CHECK (min_score >= 0 AND max_score <= 100
                                                 AND max_score >= min_score)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 18. FINAL_GRADES
-- Computed final grade for each placement (FR-11, FR-12).
-- Status lifecycle: pending → computed → coordinator_verified →
--                  management_approved → published
-- =============================================================================
CREATE TABLE final_grades (
    grade_id           INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    placement_id       INT UNSIGNED  NOT NULL,
    computed_score     DECIMAL(5,2)  NULL,
    grade_band         VARCHAR(5)    NULL,
    computation_notes  TEXT          NULL,
    verified_by        INT UNSIGNED  NULL,
    verified_at        DATETIME      NULL,
    approved_by        INT UNSIGNED  NULL,
    approved_at        DATETIME      NULL,
    published_at       DATETIME      NULL,
    status             ENUM(
                           'pending',
                           'computed',
                           'coordinator_verified',
                           'management_approved',
                           'published'
                       ) NOT NULL DEFAULT 'pending',
    CONSTRAINT pk_final_grades         PRIMARY KEY (grade_id),
    CONSTRAINT uq_final_grades_pl      UNIQUE      (placement_id),
    CONSTRAINT fk_fg_placement         FOREIGN KEY (placement_id)
        REFERENCES placements (placement_id) ON DELETE CASCADE,
    CONSTRAINT fk_fg_verified_by       FOREIGN KEY (verified_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_fg_approved_by       FOREIGN KEY (approved_by)
        REFERENCES users (user_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 19. NOTIFICATIONS
-- In-app notifications for all users (FR-13).
-- =============================================================================
CREATE TABLE notifications (
    notification_id INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    recipient_id    INT UNSIGNED  NOT NULL,
    title           VARCHAR(200)  NOT NULL,
    message         TEXT          NOT NULL,
    type            VARCHAR(50)   NULL,
    is_read         TINYINT(1)    NOT NULL DEFAULT 0,
    created_at      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_notifications      PRIMARY KEY (notification_id),
    CONSTRAINT fk_notif_recipient    FOREIGN KEY (recipient_id)
        REFERENCES users (user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 20. AUDIT_LOGS
-- Immutable record of important system events (NFR-06, NFR-11, D-05).
-- Covers: login events, lockouts, unlocks, approvals, grade changes.
-- No DELETE or UPDATE is expected on this table.
-- =============================================================================
CREATE TABLE audit_logs (
    log_id      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id     INT UNSIGNED    NULL,
    action      VARCHAR(100)    NOT NULL,
    entity_type VARCHAR(50)     NULL,
    entity_id   INT UNSIGNED    NULL,
    details     JSON            NULL,
    ip_address  VARCHAR(45)     NULL,
    created_at  DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_audit_logs     PRIMARY KEY (log_id),
    CONSTRAINT fk_al_user        FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =============================================================================
-- 21. GPS_ATTENDANCE_RECORDS
-- Additional lecturer requirement (D-04).
-- Records GPS coordinates for student attendance verification.
-- consent_given MUST be TRUE before any coordinates are stored.
-- Location data is privacy-sensitive — access restricted by role.
-- =============================================================================
CREATE TABLE gps_attendance_records (
    attendance_id   INT UNSIGNED   NOT NULL AUTO_INCREMENT,
    placement_id    INT UNSIGNED   NOT NULL,
    student_id      INT UNSIGNED   NOT NULL,
    recorded_at     DATETIME       NOT NULL,
    latitude        DECIMAL(10,7)  NOT NULL,
    longitude       DECIMAL(10,7)  NOT NULL,
    accuracy_meters DECIMAL(6,2)   NULL,
    consent_given   TINYINT(1)     NOT NULL DEFAULT 0,
    verified_status ENUM('pending','verified','rejected')
                                   NOT NULL DEFAULT 'pending',
    verified_by     INT UNSIGNED   NULL,
    notes           TEXT           NULL,
    CONSTRAINT pk_gps_attendance           PRIMARY KEY (attendance_id),
    CONSTRAINT fk_gps_placement            FOREIGN KEY (placement_id)
        REFERENCES placements (placement_id) ON DELETE CASCADE,
    CONSTRAINT fk_gps_student              FOREIGN KEY (student_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_gps_verified_by          FOREIGN KEY (verified_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT chk_gps_consent             CHECK (consent_given = 1),
    CONSTRAINT chk_latitude_range          CHECK (latitude  BETWEEN -90  AND  90),
    CONSTRAINT chk_longitude_range         CHECK (longitude BETWEEN -180 AND 180)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

